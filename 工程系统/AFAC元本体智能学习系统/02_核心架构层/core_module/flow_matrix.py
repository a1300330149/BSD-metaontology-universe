"""
归属基底：第规则相位位（第二位）
对应三界秩序：天道/自然/人道
对应公理：第2条（全域九维法理公理）、第4条（双边界守恒公理）、第5条（科研动力学公理）、第7条（递归自指公理）
对应九维维度：天道原理/天道动力学/自然相变/自然实体/社会创造/社会因果/肉身能级/精神能级/道心能级
理论原文出处：《V3.0元本体理论分册》第二章
核心数理参数：κ=0.35, γ=0.92, M7流转矩阵固定权重

本模块实现M7九维流转矩阵，管理九维状态向量之间的流转关系。

理论映射：
- M7流转矩阵：对应全域九维法理公理（公理二）
- 状态流转：对应科研动力学公理（公理五）
- 固定权重：对应锁档核心参数

固定权重（锁档核心）：
- κ = 0.35：耦合强度系数
- γ = 0.92：衰减系数
"""

import numpy as np
from src.core.global_state import GlobalState

class GlobalFlowMatrix:
    """
    功能：九维M7流转矩阵计算
    理论映射：规则相位位（第二位）·全域道运流转规则
    能级关联：e_body、e_mind、e_self三阶能级更新
    约束来源：三重具现转化公理
    禁止修改：M7固定权重，修改会破坏理论闭环

    实现九维状态向量之间的流转关系，包含固定权重矩阵和状态更新机制。

    固定权重（锁档核心）：
    - M7流转矩阵固定权重
    - κ = 0.35：耦合强度系数
    - γ = 0.92：衰减系数
    """

    def __init__(self):
        """
        初始化M7流转矩阵 - 对应全域九维法理公理（公理二）

        构建九维流转矩阵，包含固定权重配置。
        """
        self.M7 = np.zeros((9, 9))

        # 固定权重配置（锁档核心）
        # 对应九维流转关系
        self.M7[2, 1] = 0.8  # 自然相变 ← 天道动力学
        self.M7[3, 1] = 0.7  # 自然实体 ← 天道动力学
        self.M7[4, 2] = 0.6  # 社会创造 ← 自然相变
        self.M7[5, 3] = 0.7  # 社会因果 ← 自然实体
        self.M7[6, 3] = 0.5  # 肉身能级 ← 自然实体
        self.M7[7, 5] = 0.6  # 精神能级 ← 社会因果
        self.M7[8, 6] = 0.4  # 自我能级 ← 肉身能级
        self.M7[8, 7] = 0.5  # 自我能级 ← 精神能级
        self.M7[1, 5] = 0.3  # 天道动力学 ← 社会因果（反馈回路）

    def step_update(self, state: GlobalState, gamma_t=1.0):
        """
        状态步进更新 - 对应科研动力学公理（公理五）

        实现状态的递归更新，包含流转矩阵乘法和衰减项。

        Args:
            state (GlobalState): 全局状态对象
            gamma_t (float): 时间衰减系数（理论值：γ = 0.92）

        理论方程：
        S_{t+1} = M7 · S_t + γ · Δ
        其中：
        - S_t：当前状态向量
        - M7：流转矩阵
        - γ：衰减系数
        - Δ：外部扰动
        """
        vec = state.to_vector()

        # 衰减项 - 对应科研动力学公理（公理五）
        # 固定系数（锁档核心）：κ = 0.35
        gamma_in = np.ones((9, 1)) * gamma_t * 0.02

        # 流转更新 - 对应M7九维流转矩阵
        new_vec = self.M7 @ vec + gamma_in

        # 状态约束 - 对应双边界守恒公理（公理四）
        new_vec = np.clip(new_vec, 0, 1)

        # 更新状态 - 对应递归自指公理（公理七）
        state.update_from_vector(new_vec)

        # 计算自我能级 - 对应三阶变身机制
        # E_self = 0.4 · E_body + 0.6 · E_mind
        state.e_self = 0.4 * state.e_body + 0.6 * state.e_mind

        # 更新变身等级 - 对应相变临界公理（公理六）
        state.transform_level = state.check_transform_level()